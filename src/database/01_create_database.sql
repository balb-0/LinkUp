CREATE TABLE IF NOT EXISTS Usuario (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE,
  senha VARCHAR(255) NOT NULL,
  cargo VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS Profissional (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(255) NOT NULL,
  email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS Aluno (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(255) NOT NULL,
  unidade VARCHAR(255) NOT NULL,
  curso VARCHAR(255) NOT NULL,
  turno VARCHAR(255) NOT NULL,
  necessidade_especial VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS Tecnologia_Assistiva (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nome VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS Atendimento (
  id INT AUTO_INCREMENT PRIMARY KEY,
  aluno_id INT NOT NULL,
  data_atendimento DATETIME NOT NULL,
  tipo_atendimento VARCHAR(255) NOT NULL,
  profissional_id INT NOT NULL,
  tecnologia_assistiva_id INT,
  FOREIGN KEY (aluno_id) REFERENCES Aluno(id) ON DELETE CASCADE,
  FOREIGN KEY (profissional_id) REFERENCES Profissional(id) ON DELETE CASCADE,
  FOREIGN KEY (tecnologia_assistiva_id) REFERENCES Tecnologia_Assistiva(id) ON DELETE SET NULL
);